"""
Two-qubit controlled-Z synthesis under correlated dephasing (manuscript Sec. 6.8, Fig. 11).

This script re-runs the JAX/L-BFGS-B pipeline of the original notebook
"SP OCP RSE-Copy4.ipynb" (Blocks 18-21) with fixed, documented seeds, and adds the
Monte Carlo robustness evaluation that the manuscript describes. It replaces the
earlier Fig. 11, which had been generated by a mock-data test block
(np.random.normal(0.99, 0.005, 500)) rather than by simulation.

Model (identical to Blocks 18-21):
  H(t) = 0.5 sz(x)sz + u1x sx1 + u1y sy1 + u2x sx2 + u2y sy2 + eta1 sz1 + eta2 sz2,
  T = 10, N = 150 steps on time_grid = linspace(0, T, 150), h = T/N,
  exact stepwise exponentials (jax.scipy.linalg.expm),
  controls: truncated Fourier series, 5 harmonics per line (40 coefficients),
  objective: mean infidelity over 5 training dephasing realizations per qubit
             + lam * h * sum sqrt(lx(u1x^2+u2x^2) + ly(u1y^2+u2y^2)), lam=1e-4, lx=1, ly=4,
  optimizer: L-BFGS-B (maxiter 400, ftol 1e-9), bounds +-8, initial guesses
             uniform(-4,4) with seeds 999+7a, up to 10 restarts, stopping at the first
             restart whose clean infidelity is below 1e-2 (as in Block 20).
Noise: Matern nu=3/2, sigma=0.05, ell=0.4, truncated at 3 sigma (essential boundedness),
       training seed 4242, validation seed 777 (disjoint), 1000 validation realizations.

Usage:
  python cz_experiment.py             re-runs the optimization, then the Monte Carlo evaluation
  python cz_experiment.py published   evaluates the published coefficients in
                                      data/cz_coeffs_published.npy (reproduces Sec. 6.8 exactly)
Outputs go to ./out_cz/ or ./out_cz_published/.
L-BFGS trajectories are sensitive to round-off, so a re-optimization on other hardware or
software versions can return a slightly different local optimum (see Sec. 6.8).
"""
import os, sys, json, time
import numpy as np
import jax
jax.config.update("jax_enable_x64", True)
import jax.numpy as jnp
from jax.scipy.linalg import expm as jexpm
from scipy.optimize import minimize

HERE = os.path.dirname(os.path.abspath(__file__))
PUBLISHED = len(sys.argv) > 1 and sys.argv[1] == 'published'
OUT = os.path.join(HERE, 'out_cz_published' if PUBLISHED else 'out_cz')
os.makedirs(OUT, exist_ok=True)

sx = np.array([[0, 1], [1, 0]], complex); sy = np.array([[0, -1j], [1j, 0]], complex)
sz = np.array([[1, 0], [0, -1]], complex); I2 = np.eye(2, dtype=complex)
K = lambda a, b: jnp.array(np.kron(a, b))
SX1, SY1, SX2, SY2 = K(sx, I2), K(sy, I2), K(I2, sx), K(I2, sy)
SZ1, SZ2, HD = K(sz, I2), K(I2, sz), 0.5 * K(sz, sz)
CZ = jnp.diag(jnp.array([1, 1, 1, -1], dtype=jnp.complex128))

T, N = 10.0, 150
tg = np.linspace(0, T, N)          # as in the original notebook
h = T / N
NF = 5
LAM, LX, LY = 1e-4, 1.0, 4.0
SIGMA, ELL, CLIP = 0.05, 0.4, 3.0


def matern_noise(rng, S):
    r = np.abs(tg[:, None] - tg[None, :])
    f = np.sqrt(3) * r / ELL
    Kc = (1 + f) * np.exp(-f) + 1e-10 * np.eye(N)
    L = np.linalg.cholesky(Kc)
    z = (L @ rng.standard_normal((N, S))).T
    return SIGMA * np.clip(z, -CLIP, CLIP)


_sin = jnp.array([np.sin((k + 1) * np.pi * tg / T) for k in range(NF)])
_cos = jnp.array([np.cos((k + 1) * np.pi * tg / T) for k in range(NF)])


def pulses(c):
    c = c.reshape(4, NF, 2)                     # line, harmonic, (a_k, b_k)
    return c[:, :, 0] @ _sin + c[:, :, 1] @ _cos  # (4, N): u1x, u1y, u2x, u2y


def propagate(u, e1, e2):
    def step(U, k):
        H = (HD + u[0, k] * SX1 + u[1, k] * SY1 + u[2, k] * SX2 + u[3, k] * SY2
             + e1[k] * SZ1 + e2[k] * SZ2)
        return jexpm(-1j * h * H) @ U, None
    U, _ = jax.lax.scan(step, jnp.eye(4, dtype=jnp.complex128), jnp.arange(N))
    return U


def infid(U):
    return 1.0 - jnp.abs(jnp.trace(CZ.conj().T @ U)) / 4.0


def objective(c, n1, n2):
    u = pulses(c)
    gate = jnp.mean(jax.vmap(lambda a, b: infid(propagate(u, a, b)))(n1, n2))
    pen = h * jnp.sum(jnp.sqrt(LX * (u[0] ** 2 + u[2] ** 2) + LY * (u[1] ** 2 + u[3] ** 2)))
    return gate + LAM * pen


obj_grad = jax.jit(jax.value_and_grad(objective))
clean_infid = jax.jit(lambda c: infid(propagate(pulses(c), jnp.zeros(N), jnp.zeros(N))))
batch_infid = jax.jit(lambda c, n1, n2: jax.vmap(lambda a, b: infid(propagate(pulses(c), a, b)))(n1, n2))


def main():
    rng_tr = np.random.default_rng(4242)
    n1, n2 = jnp.array(matern_noise(rng_tr, 5)), jnp.array(matern_noise(rng_tr, 5))
    wrap = lambda c: tuple(np.array(x, dtype=np.float64) for x in obj_grad(jnp.array(c), n1, n2))
    if PUBLISHED:
        t0 = time.perf_counter()
        c0 = np.load(os.path.join(HERE, 'data', 'cz_coeffs_published.npy'))
        best = (c0, float(clean_infid(jnp.array(c0))), 400); log = []
        print(f'published coefficients: clean infidelity {best[1]:.3e}', flush=True)
    else:
        t0 = time.perf_counter()
        best = None; log = []
        for a in range(10):
            c0 = np.random.default_rng(999 + 7 * a).uniform(-4.0, 4.0, 40)
            res = minimize(wrap, c0, method='L-BFGS-B', jac=True, bounds=[(-8.0, 8.0)] * 40,
                           options={'maxiter': 400, 'ftol': 1e-9})
            ci = float(clean_infid(jnp.array(res.x)))
            log.append(dict(restart=a + 1, clean_infidelity=ci, objective=float(res.fun), nit=int(res.nit)))
            print(f'restart {a+1}: clean infidelity {ci:.3e}, objective {res.fun:.3e}, iterations {res.nit}', flush=True)
            if best is None or ci < best[1]:
                best = (res.x.copy(), ci, int(res.nit))
            if best[1] < 1e-2:
                break
    wall = time.perf_counter() - t0
    c = jnp.array(best[0])
    # Monte Carlo robustness on disjoint validation noise
    rng_v = np.random.default_rng(777)
    S = 1000
    v1, v2 = jnp.array(matern_noise(rng_v, S)), jnp.array(matern_noise(rng_v, S))
    F = 1.0 - np.array(batch_infid(c, v1, v2))
    u = np.array(pulses(c))
    res = dict(clean_fidelity=1 - best[1], clean_infidelity=best[1], iterations=best[2],
               restarts_used=len(log), restart_log=log, wall_s=wall,
               mc_samples=S, mc_mean=float(F.mean()), mc_std=float(F.std()), mc_median=float(np.median(F)),
               mc_min=float(F.min()), mc_max=float(F.max()), mc_mean_infidelity=float(1 - F.mean()),
               J_noise=float(h * np.sum(np.sqrt(LX * (u[0] ** 2 + u[2] ** 2) + LY * (u[1] ** 2 + u[3] ** 2)))),
               max_abs_control=float(np.abs(u).max()))
    json.dump(res, open(os.path.join(OUT, 'cz_results.json'), 'w'), indent=1)
    np.save(os.path.join(OUT, 'cz_coeffs.npy'), best[0]); np.save(os.path.join(OUT, 'cz_mc_fidelities.npy'), F)
    print(json.dumps({k: v for k, v in res.items() if k != 'restart_log'}, indent=1))

    import matplotlib.pyplot as plt
    plt.rcParams.update({'font.family': 'serif', 'font.size': 12, 'axes.labelsize': 14,
                         'axes.titlesize': 14, 'mathtext.fontset': 'cm'})
    plt.figure(figsize=(8, 5))
    plt.hist(F, bins=40, alpha=0.75, color='#8c564b', edgecolor='black')
    plt.axvline(F.mean(), color='black', ls='--', lw=2, label=f'mean $\\mathcal{{F}}$ = {F.mean():.5f}')
    plt.axvline(1 - best[1], color='tab:blue', ls=':', lw=2, label=f'noiseless $\\mathcal{{F}}$ = {1-best[1]:.5f}')
    txt = f'{S} validation realizations\nmin $\\mathcal{{F}}$ = {F.min():.5f}\nstd = {F.std():.2e}'
    plt.text(0.03, 0.95, txt, transform=plt.gca().transAxes, va='top', fontsize=11,
             bbox=dict(facecolor='white', alpha=0.85, edgecolor='black'))
    plt.xlabel(r'CZ gate fidelity $\mathcal{F}$'); plt.ylabel('Frequency')
    plt.title('Two-qubit CZ gate under correlated dephasing')
    plt.legend(loc='center left', fontsize=10); plt.grid(alpha=0.4, ls='--')
    plt.tight_layout()
    plt.savefig(os.path.join(OUT, 'figure9_CZ_histogram.png'), dpi=300)
    plt.savefig(os.path.join(OUT, 'figure9_CZ_histogram.pdf'))
    print('figure saved')


if __name__ == '__main__':
    main()
